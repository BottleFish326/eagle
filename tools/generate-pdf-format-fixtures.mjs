import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { lstat, mkdir, open, readFile, rename, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repository = path.resolve(import.meta.dirname, "..");
const sourceRoot = path.join(repository, "fixtures", "formats", "sources");

export const GENERATED_PDF_FIXTURES = Object.freeze([
  "pdf/minimal.pdf",
  "pdf/active-javascript.pdf",
  "pdf/external-uri.pdf",
  "pdf/truncated.pdf",
  "pdf/png-disguised-as-pdf.pdf",
  "pdf/pdf-disguised-as-png.png",
  "pdf/encrypted.pdf",
  "pdf/object-stream.pdf",
  "pdf/oversized-page-count.pdf",
  "pdf/oversized-page-dimensions.pdf",
]);

function buildClassicPdf({
  catalogExtra = "",
  mediaBox = "[0 0 612 792]",
  declaredPageCount = 2,
  extraObjects = [],
  trailerExtra = "",
} = {}) {
  const objects = [
    `<< /Type /Catalog /Pages 2 0 R ${catalogExtra} >>`,
    `<< /Type /Pages /Kids [3 0 R 4 0 R] /Count ${declaredPageCount} >>`,
    `<< /Type /Page /Parent 2 0 R /MediaBox ${mediaBox} /Contents 5 0 R >>`,
    "<< /Type /Page /Parent 2 0 R /Contents 5 0 R >>",
    "<< /Length 0 >>\nstream\n\nendstream",
    ...extraObjects,
  ];
  const chunks = [Buffer.from("%PDF-1.7\n%\xe2\xe3\xcf\xd3\n", "binary")];
  const offsets = [0];
  let length = chunks[0].length;
  for (const [index, body] of objects.entries()) {
    offsets.push(length);
    const chunk = Buffer.from(
      `${index + 1} 0 obj\n${body}\nendobj\n`,
      "binary",
    );
    chunks.push(chunk);
    length += chunk.length;
  }
  const xrefOffset = length;
  const xref = [
    `xref\n0 ${objects.length + 1}\n`,
    "0000000000 65535 f \n",
    ...offsets
      .slice(1)
      .map((offset) => `${String(offset).padStart(10, "0")} 00000 n \n`),
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R ${trailerExtra} >>\n`,
    `startxref\n${xrefOffset}\n%%EOF\n`,
  ].join("");
  chunks.push(Buffer.from(xref, "binary"));
  return Buffer.concat(chunks);
}

export function buildPdfFormatFixtures(referencePng) {
  const minimal = buildClassicPdf();
  return new Map([
    ["pdf/minimal.pdf", minimal],
    [
      "pdf/active-javascript.pdf",
      buildClassicPdf({
        catalogExtra: "/OpenAction 6 0 R",
        extraObjects: ["<< /S /JavaScript /JS (app.alert\\(1\\)) >>"],
      }),
    ],
    [
      "pdf/external-uri.pdf",
      buildClassicPdf({
        catalogExtra: "/OpenAction 6 0 R",
        extraObjects: ["<< /S /URI /URI (https://example.invalid/) >>"],
      }),
    ],
    ["pdf/truncated.pdf", minimal.subarray(0, minimal.indexOf("xref"))],
    ["pdf/png-disguised-as-pdf.pdf", referencePng],
    ["pdf/pdf-disguised-as-png.png", minimal],
    [
      "pdf/encrypted.pdf",
      buildClassicPdf({
        extraObjects: ["<< /Filter /Standard /V 1 /R 2 /O () /U () /P -4 >>"],
        trailerExtra: "/Encrypt 6 0 R /ID [(fixture)(fixture)]",
      }),
    ],
    [
      "pdf/object-stream.pdf",
      buildClassicPdf({
        extraObjects: [
          "<< /Type /ObjStm /N 0 /First 0 /Length 0 >>\nstream\n\nendstream",
        ],
      }),
    ],
    [
      "pdf/oversized-page-count.pdf",
      buildClassicPdf({ declaredPageCount: 100_001 }),
    ],
    [
      "pdf/oversized-page-dimensions.pdf",
      buildClassicPdf({ mediaBox: "[0 0 70000 792]" }),
    ],
  ]);
}

export async function generatePdfFormatFixtures({
  replaceExisting = false,
} = {}) {
  const referencePng = await readFile(
    path.join(
      repository,
      "fixtures",
      "formats",
      "references",
      "svg",
      "minimal.png",
    ),
  );
  const fixtures = buildPdfFormatFixtures(referencePng);
  for (const relativePath of GENERATED_PDF_FIXTURES) {
    await writeFixedFixture(
      relativePath,
      fixtures.get(relativePath),
      replaceExisting,
    );
  }
  return fixtures;
}

async function writeFixedFixture(relativePath, bytes, replaceExisting) {
  assert.ok(bytes, `missing generated bytes for ${relativePath}`);
  const target = path.resolve(sourceRoot, relativePath);
  if (!target.startsWith(`${sourceRoot}${path.sep}`)) {
    throw new Error(`generated fixture escapes source root: ${relativePath}`);
  }
  await mkdir(path.dirname(target), { recursive: true });
  try {
    const metadata = await lstat(target);
    if (metadata.isSymbolicLink() || !metadata.isFile()) {
      throw new Error(
        `generated fixture target is not a regular file: ${relativePath}`,
      );
    }
    const existing = await readFile(target);
    if (!existing.equals(bytes) && !replaceExisting) {
      throw new Error(
        `generated fixture differs from deterministic output: ${relativePath}`,
      );
    }
    if (existing.equals(bytes)) return;
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  const temporary = `${target}.generate-${process.pid}-${randomUUID()}.tmp`;
  let temporaryOwned = false;
  try {
    const handle = await open(temporary, "wx", 0o644);
    temporaryOwned = true;
    try {
      await handle.writeFile(bytes);
      await handle.sync();
    } finally {
      await handle.close();
    }
    await rename(temporary, target);
    temporaryOwned = false;
  } finally {
    if (temporaryOwned) await unlink(temporary).catch(() => {});
  }
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.some((argument) => argument !== "--replace")) {
    throw new Error(
      "usage: node tools/generate-pdf-format-fixtures.mjs [--replace]",
    );
  }
  const fixtures = await generatePdfFormatFixtures({
    replaceExisting: arguments_.includes("--replace"),
  });
  console.log(
    JSON.stringify(
      {
        schema: 1,
        fixtures: [...fixtures].map(([fixturePath, bytes]) => ({
          path: `sources/${fixturePath}`,
          size: bytes.length,
          sha256: createHash("sha256").update(bytes).digest("hex"),
        })),
      },
      null,
      2,
    ),
  );
}

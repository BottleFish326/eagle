import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { lstat, mkdir, open, readFile, rename, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repository = path.resolve(import.meta.dirname, "..");
const formatRoot = path.join(repository, "fixtures", "formats");
const sourceRoot = path.join(formatRoot, "sources");

export const GENERATED_AVIF_FIXTURES = Object.freeze([
  "avif/corrupted-bitstream.avif",
  "avif/truncated-ftyp.avif",
  "avif/png-disguised-as-avif.avif",
  "avif/avif-disguised-as-jpeg.jpg",
  "avif/unknown-codec.avif",
  "avif/oversized-ispe.avif",
  "avif/resource-limited-output.avif",
]);

export function buildAdversarialAvifFixtures({ sourceAvif, referencePng }) {
  assert.equal(
    createHash("sha256").update(sourceAvif).digest("hex"),
    "54a0dc31d02b6f5d9d4b66027d4787861b7af15ffd8fab8eab963d10c5411469",
    "the pinned source AVIF changed",
  );
  assert.equal(sourceAvif.indexOf("av01"), 178, "unexpected AV1 item offset");
  assert.equal(
    sourceAvif.indexOf("av01", 179),
    -1,
    "source AVIF has multiple AV1 item markers",
  );
  assert.equal(sourceAvif.indexOf("ispe"), 234, "unexpected ispe offset");
  assert.equal(sourceAvif.indexOf("mdat"), 276, "unexpected mdat offset");
  assert.equal(sourceAvif.readUInt32BE(242), 800, "unexpected source width");
  assert.equal(sourceAvif.readUInt32BE(246), 533, "unexpected source height");
  assert.ok(
    referencePng.subarray(0, 8).equals(Buffer.from("89504e470d0a1a0a", "hex")),
    "reference is not PNG",
  );

  const unknownCodec = Buffer.from(sourceAvif);
  unknownCodec.write("jpeg", 178, "ascii");

  const oversized = Buffer.from(sourceAvif);
  oversized.writeUInt32BE(65_536, 242);

  const corrupted = Buffer.from(sourceAvif);
  corrupted.fill(0, 280);

  return new Map([
    ["avif/corrupted-bitstream.avif", corrupted],
    ["avif/truncated-ftyp.avif", sourceAvif.subarray(0, 24)],
    ["avif/png-disguised-as-avif.avif", Buffer.from(referencePng)],
    ["avif/avif-disguised-as-jpeg.jpg", Buffer.from(sourceAvif)],
    ["avif/unknown-codec.avif", unknownCodec],
    ["avif/oversized-ispe.avif", oversized],
    ["avif/resource-limited-output.avif", Buffer.from(sourceAvif)],
  ]);
}

export async function generateAdversarialFormatFixtures({
  replaceExisting = false,
} = {}) {
  const sourceAvif = await readFile(
    path.join(sourceRoot, "avif", "libheif-example.avif"),
  );
  const referencePng = await readFile(
    path.join(formatRoot, "references", "svg", "minimal.png"),
  );
  const fixtures = buildAdversarialAvifFixtures({
    sourceAvif,
    referencePng,
  });

  for (const relativePath of GENERATED_AVIF_FIXTURES) {
    const bytes = fixtures.get(relativePath);
    assert.ok(bytes, `missing generated bytes for ${relativePath}`);
    await writeFixedFixture(relativePath, bytes, replaceExisting);
  }
  return fixtures;
}

async function writeFixedFixture(relativePath, bytes, replaceExisting) {
  const target = path.resolve(sourceRoot, relativePath);
  if (!target.startsWith(`${sourceRoot}${path.sep}`)) {
    throw new Error(`generated fixture escapes source root: ${relativePath}`);
  }
  await mkdir(path.dirname(target), { recursive: true });

  try {
    const metadata = await lstat(target);
    if (metadata.isSymbolicLink() || !metadata.isFile()) {
      throw new Error(
        `generated fixture target is not a regular file: ${relativePath}`,
      );
    }
    const existing = await readFile(target);
    if (!existing.equals(bytes) && !replaceExisting) {
      throw new Error(
        `generated fixture differs from deterministic output: ${relativePath}`,
      );
    }
    if (existing.equals(bytes)) return;
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  const temporary = `${target}.generate-${process.pid}-${randomUUID()}.tmp`;
  let temporaryOwned = false;
  try {
    const handle = await open(temporary, "wx", 0o644);
    temporaryOwned = true;
    try {
      await handle.writeFile(bytes);
      await handle.sync();
    } finally {
      await handle.close();
    }
    await rename(temporary, target);
    temporaryOwned = false;
  } finally {
    if (temporaryOwned) await unlink(temporary).catch(() => {});
  }
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.some((argument) => argument !== "--replace")) {
    throw new Error(
      "usage: node tools/generate-adversarial-format-fixtures.mjs [--replace]",
    );
  }
  const fixtures = await generateAdversarialFormatFixtures({
    replaceExisting: arguments_.includes("--replace"),
  });
  const report = [...fixtures].map(([fixturePath, bytes]) => ({
    path: `sources/${fixturePath}`,
    size: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  }));
  console.log(JSON.stringify({ schema: 1, fixtures: report }, null, 2));
}
